def above(pts, prof):
    """Pieces of `pts` lying above the polyline `prof` (sorted by x)."""
    def py(x):
        if x <= prof[0][0] or x >= prof[-1][0]:
            return -1e9
        for a, b in zip(prof, prof[1:]):
            if a[0] <= x <= b[0]:
                return a[1] + (b[1] - a[1]) * (x - a[0]) / ((b[0] - a[0]) or 1)
        return -1e9
    runs, cur = [], []
    for p in pts:
        if p[1] > py(p[0]):
            cur.append(p)
        elif cur:
            runs.append(cur)
            cur = []
    if cur:
        runs.append(cur)
    if len(runs) > 1 and runs[0][0] == runs[-1][-1]:
        runs[0] = runs.pop() + runs[0][1:]
    return [r for r in runs if len(r) > 1]


