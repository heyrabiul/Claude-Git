def spl(pts, closed=True, res=14, tension=0.5):
    """Smooth Catmull-Rom outline through `pts`; a point given as (x, y, 0)
    is a sharp corner."""
    P = [(p[0], p[1]) for p in pts]
    sharp = [len(p) > 2 and p[2] == 0 for p in pts]
    m = len(P)

    def tan(i):
        if sharp[i]:
            return (0.0, 0.0)
        if closed:
            a, b = P[(i - 1) % m], P[(i + 1) % m]
        else:
            a, b = P[max(i - 1, 0)], P[min(i + 1, m - 1)]
        return ((b[0] - a[0]) * tension, (b[1] - a[1]) * tension)

    out = [P[0]]
    for i in range(m if closed else m - 1):
        p0, p1 = P[i], P[(i + 1) % m]
        t0, t1 = tan(i), tan((i + 1) % m)
        n = max(3, int(math.dist(p0, p1) * res))
        for k in range(1, n + 1):
            t = k / n
            h00, h10, h01, h11 = 2 * t**3 - 3 * t**2 + 1, t**3 - 2 * t**2 + t, -2 * t**3 + 3 * t**2, t**3 - t**2
            out.append((h00 * p0[0] + h10 * t0[0] + h01 * p1[0] + h11 * t1[0],
                        h00 * p0[1] + h10 * t0[1] + h01 * p1[1] + h11 * t1[1]))
    return out


def sides(center, w):
    """The two edges of a band along `center` (no end caps), as two strokes."""
    band = tube(center, w, cap=False)
    n = len(center)
    return [band[:n], band[n:][::-1]]


def fringe(line, amp, teeth):
    """Zig-zag fur along a polyline: every other point pushed out by `amp`
    to the left of the direction of travel."""
    L = [0.0]
    for a, b in zip(line, line[1:]):
        L.append(L[-1] + math.dist(a, b))
    out, j = [], 0
    for k in range(2 * teeth + 1):
        d = L[-1] * k / (2 * teeth)
        while j < len(L) - 2 and L[j + 1] < d:
            j += 1
        a, b = line[j], line[j + 1]
        f = (d - L[j]) / ((L[j + 1] - L[j]) or 1)
        x, y = a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f
        ln = math.dist(a, b) or 1
        nx, ny = -(b[1] - a[1]) / ln, (b[0] - a[0]) / ln
        o = amp if k % 2 else 0.0
        out.append((x + nx * o, y + ny * o))
    return out


def outside(pts, cx, cy, r):
    """The longest run of `pts` lying outside the circle (cx, cy, r)."""
    flags = [math.hypot(x - cx, y - cy) > r for x, y in pts]
    if all(flags):
        return pts
    k = flags.index(False)
    pts, flags = pts[k:] + pts[1:k + 1], flags[k:] + flags[1:k + 1]
    runs, cur = [], []
    for p, f in zip(pts, flags):
        if f:
            cur.append(p)
        elif cur:
            runs.append(cur)
            cur = []
    if cur:
        runs.append(cur)
    return max(runs, key=len)


def spots(pts, r=0.13):
    return [circle(x, y, r, 14) for x, y in pts]


def rosettes(pts, r=0.16):
    return [arc(x, y, r, 0.4 + k, 0.4 + k + 4.6, 12) for k, (x, y) in enumerate(pts)]


def grass_tuft(x, y, s=1.0):
    return [quad((x, y), (x + dx * 0.4 * s, y + h * 0.6 * s), (x + dx * s, y + h * s), 10)
            for dx, h in [(-0.35, 0.6), (0.0, 0.8), (0.35, 0.6)]]


